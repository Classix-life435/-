// ------------------------------------------------------------
// 会話データを簡潔なタプルから組み立てるヘルパー。
// turns から isInterview（3ターン以上）を自動導出し、
// テンプレートを turns 分だけ切り出して messages を生成する。
// ------------------------------------------------------------
type Row = [
  category: string,
  language: Language,
  turns: number,
  reachedInterview: boolean,
  acqs: [number, number, number, number],
  dateISO: string,
];

function buildConversation(id: string, row: Row): Conversation {
  const [category, language, turns, reachedInterview, acqs, dateISO] = row;
  const tpl = dialogues[category];
  const msgCount = Math.min(turns * 2, tpl.ja.length);
  const messages = tpl.ja.slice(0, msgCount).map((m) => ({ ...m }));
  // 外国語の会話は、一言目を原語に差し替える（多言語アップセルの物語）
  const opener = foreignOpeners[category]?.[language];
  if (opener && messages[0]?.role === "applicant") {
    messages[0] = { role: "applicant", text: opener };
  }
  const isInterview = turns >= 3;
  return {
    id,
    jobCategory: tpl.jobCategory,
    language,
    turns,
    isInterview,
    questionCategory: category,
    // 1〜2ターンで離脱した会話は面接成立に至らず、面接へも進めない
    reachedInterview: isInterview ? reachedInterview : false,
    acqs: { q: acqs[0], a: acqs[1], e: acqs[2], p: acqs[3] },
    timestamp: dateISO,
    messages,
  };
}

